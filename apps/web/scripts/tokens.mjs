// Writes src/styles/tokens.css from the design file's exported tokens (Light on :root, Dark on the two dark selectors).
// Run after the tokens change: node scripts/tokens.mjs
import { readFileSync, writeFileSync } from "node:fs";
const css = readFileSync(new URL("../../../.context/design/figcraft/tokens/sgsi-tokens.css", import.meta.url), "utf8");
const pick = (re) => css.match(re)[1].replace(/--([a-z]+)-\1(?=[-:])/g, "--$1");
const light = pick(/:root\s*\{([\s\S]*?)\}/), dark = pick(/\[data-sgsi-tokens="Dark"\]\s*\{([\s\S]*?)\}/);
writeFileSync(new URL("../src/styles/tokens.css", import.meta.url),
  "/* Generated by scripts/tokens.mjs from .context/design/figcraft/tokens/sgsi-tokens.css. Do not edit by hand. */\n" +
  ":root {" + light + "}\n@media (prefers-color-scheme: dark) { :root:not([data-theme=\"light\"]) {" + dark + " color-scheme: dark; } }\n" +
  ":root[data-theme=\"dark\"] {" + dark + " color-scheme: dark; }\n");
console.log("tokens.css written");
